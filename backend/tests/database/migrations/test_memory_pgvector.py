def test_qualified_vector_reflection_and_drift_detection_under_hardened_search_path(
    database_url: str, monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setenv("AIDAM_MIGRATION_REQUIRE_TLS", "false")
    monkeypatch.setenv("AIDAM_MIGRATION_ROLE", "aidam_owner")
    config = _config(database_url)
    command.upgrade(config, "0014")
    engine = sa.create_engine(database_url)
    with warnings.catch_warnings():
        warnings.simplefilter("error", sa.exc.SAWarning)
        with engine.begin() as connection:
            connection.execute(sa.text("SET LOCAL search_path = pg_catalog"))
            columns = sa.inspect(connection).get_columns("memory_search_embeddings", schema="memory")
            embedding_type = next(column["type"] for column in columns if column["name"] == "embedding")
            assert isinstance(embedding_type, Vector)
            assert embedding_type.dim is None
        command.check(config)

        # Prove comparison is active, rather than a clean check silently skipping
        # an unknown type. This disposable DB deliberately drifts back to arrays.
        with engine.begin() as connection:
            connection.execute(sa.text("""
                ALTER TABLE memory.memory_search_embeddings
                DROP CONSTRAINT ck_memory_search_embeddings_embedding_dimensions
            """))
            connection.execute(sa.text("""
                ALTER TABLE memory.memory_search_embeddings
                ALTER COLUMN embedding TYPE double precision[]
                USING embedding::real[]::double precision[]
            """))
        with pytest.raises(AutogenerateDiffsDetected, match="modify_type"):
            command.check(config)
    engine.dispose()
